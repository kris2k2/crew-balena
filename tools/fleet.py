#!/usr/bin/env python3
"""Render and check the balenaCloud fleets this repository deploys.

A fleet is fleets/<id>.yml: the balenaCloud fleet it targets, the fleet
release version, whether deploying is on, and the services it runs, each
pinned to a released version. A service is services/<name>/: the project's
block, plus one directory per vendored release holding the project's compose
fragment copied verbatim from that release's tag.

Rendering a fleet substitutes each service's block and version into its
fragment, merges the fragments into one docker-compose.yml, and writes the
balena.yml that names the fleet release. That directory is what
`balena push <fleet> --source` takes.

  fleet.py check [--base-root DIR]     validate every fleet and the services it
                                       pins; with a base tree, also require a
                                       version bump wherever the rendered
                                       composition changed
  fleet.py render [ID ...] --out DIR   write <DIR>/<id>/source/ and <DIR>/<id>/meta.json
  fleet.py changed --base-root DIR     ids of the fleets a merge should push:
                                       deploying is on, and the fleet is new,
                                       just switched on, or renders differently

Every failure is an error with the file it is about; nothing is guessed. A
composition that is wrong reaches devices nobody can get at, so this fails
closed.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent

# The strings a project's fragment carries in place of a real image reference.
# The same two crew-printcapture's own deploy.sh substitutes, so a fragment is
# vendored verbatim and needs no rewriting for this repository.
SLUG_PLACEHOLDER = "BALENA_BLOCK_SLUG"
VERSION_PLACEHOLDER = "BALENA_BLOCK_VERSION"
IMAGE_PLACEHOLDER = f"bh.cr/{SLUG_PLACEHOLDER}/{VERSION_PLACEHOLDER}"

# Names that end up in paths are held to these, so a manifest cannot point a
# render outside services/ or fleets/.
FLEET_ID = re.compile(r"^[a-z0-9][a-z0-9-]*$")
SERVICE_NAME = re.compile(r"^[a-z0-9][a-z0-9-]*$")
# balena handles are lowercase; `<organization>/<fleet or block>`.
BALENA_SLUG = re.compile(r"^[a-z0-9][a-z0-9_-]*/[a-z0-9][a-z0-9_-]*$")
REPOSITORY = re.compile(r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")
# balena requires 3-digit semver for release versions, and renders anything
# else as 0.0.0.
SEMVER = re.compile(r"^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$")
SHA1 = re.compile(r"^[0-9a-f]{40}$")
SHA256 = re.compile(r"^[0-9a-f]{64}$")

FLEET_KEYS = {"name", "slug", "version", "deploy", "services"}
SERVICE_KEYS = {"repository", "fragment", "block"}
SOURCE_KEYS = {"tag", "commit", "sha256"}
# Top-level compose keys a fragment may use. Anything else (networks, secrets,
# configs) would need a merge rule this tool does not have yet, so it is
# refused rather than silently dropped.
COMPOSE_KEYS = {"version", "services", "volumes"}

GENERATED_HEADER = (
    "# Generated by crew-balena tools/fleet.py from fleets/{id}.yml. Do not edit:\n"
    "# change the manifest or vendor a new service release instead.\n"
)


class FleetError(Exception):
    """A manifest, service, or fragment that cannot be deployed as it stands."""


def semver(text: str) -> tuple:
    return tuple(int(part) for part in text.split("."))


def _load_yaml(path: Path) -> object:
    try:
        return yaml.safe_load(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise FleetError(f"{path}: missing") from None
    except yaml.YAMLError as exc:
        raise FleetError(f"{path}: not valid YAML: {exc}") from None


def _mapping(path: Path, data: object, keys: set) -> dict:
    if not isinstance(data, dict):
        raise FleetError(f"{path}: expected a mapping")
    missing = keys - data.keys()
    unknown = data.keys() - keys
    if missing:
        raise FleetError(f"{path}: missing {', '.join(sorted(missing))}")
    if unknown:
        raise FleetError(f"{path}: unknown {', '.join(sorted(map(str, unknown)))}")
    return data


def _string(path: Path, data: dict, key: str, pattern: re.Pattern | None = None) -> str:
    value = data[key]
    # YAML reads `1.15` as a float and `2.0.0` as a string; requiring a string
    # catches the first before it renders as a different version.
    if not isinstance(value, str) or not value:
        raise FleetError(f"{path}: {key} must be a non-empty string (quote it)")
    if pattern is not None and not pattern.match(value):
        raise FleetError(f"{path}: {key} {value!r} does not match {pattern.pattern}")
    return value


def load_service(root: Path, name: str) -> dict:
    path = root / "services" / name / "service.yml"
    data = _mapping(path, _load_yaml(path), SERVICE_KEYS)
    return {
        "repository": _string(path, data, "repository", REPOSITORY),
        "fragment": _string(path, data, "fragment"),
        "block": _string(path, data, "block", BALENA_SLUG),
    }


def load_fragment(root: Path, name: str, version: str) -> str:
    """The vendored fragment for one release, after checking it is unedited."""
    directory = root / "services" / name / version
    source_path = directory / "source.yml"
    source = _mapping(source_path, _load_yaml(source_path), SOURCE_KEYS)
    tag = _string(source_path, source, "tag")
    if tag != f"v{version}":
        raise FleetError(f"{source_path}: tag {tag} does not name version {version}")
    _string(source_path, source, "commit", SHA1)
    expected = _string(source_path, source, "sha256", SHA256)

    fragment_path = directory / "docker-compose.yml"
    try:
        raw = fragment_path.read_bytes()
    except FileNotFoundError:
        raise FleetError(f"{fragment_path}: missing") from None
    actual = hashlib.sha256(raw).hexdigest()
    if actual != expected:
        raise FleetError(
            f"{fragment_path}: sha256 {actual} is not the {expected} recorded in "
            f"{source_path}. Vendored fragments are copied verbatim from the "
            f"project's release tag and never edited here."
        )
    return raw.decode("utf-8")


def load_fleet(root: Path, fleet_id: str) -> dict:
    if not FLEET_ID.match(fleet_id):
        raise FleetError(f"fleet id {fleet_id!r} does not match {FLEET_ID.pattern}")
    path = root / "fleets" / f"{fleet_id}.yml"
    data = _mapping(path, _load_yaml(path), FLEET_KEYS)
    if not isinstance(data["deploy"], bool):
        raise FleetError(f"{path}: deploy must be true or false")
    services = data["services"]
    if not isinstance(services, dict) or not services:
        raise FleetError(f"{path}: services must map at least one service to a version")
    for name, version in services.items():
        if not isinstance(name, str) or not SERVICE_NAME.match(name):
            raise FleetError(f"{path}: service name {name!r} does not match {SERVICE_NAME.pattern}")
        if not isinstance(version, str) or not SEMVER.match(version):
            raise FleetError(f"{path}: {name} version {version!r} is not a quoted X.Y.Z")
    return {
        "id": fleet_id,
        "name": _string(path, data, "name"),
        "slug": _string(path, data, "slug", BALENA_SLUG),
        "version": _string(path, data, "version", SEMVER),
        "deploy": data["deploy"],
        "services": dict(services),
    }


def fleet_ids(root: Path) -> list:
    return sorted(p.stem for p in (root / "fleets").glob("*.yml"))


def _service_compose(root: Path, name: str, version: str) -> dict:
    service = load_service(root, name)
    text = load_fragment(root, name, version)
    where = f"services/{name}/{version}/docker-compose.yml"
    if IMAGE_PLACEHOLDER not in text:
        raise FleetError(f"{where}: no `image: {IMAGE_PLACEHOLDER}` to substitute")
    image = f"bh.cr/{service['block']}/{version}"
    text = text.replace(IMAGE_PLACEHOLDER, image)
    if SLUG_PLACEHOLDER in text or VERSION_PLACEHOLDER in text:
        raise FleetError(f"{where}: a placeholder is left outside `image: {IMAGE_PLACEHOLDER}`")
    try:
        doc = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise FleetError(f"{where}: not valid YAML: {exc}") from None
    if not isinstance(doc, dict):
        raise FleetError(f"{where}: expected a compose mapping")
    unknown = doc.keys() - COMPOSE_KEYS
    if unknown:
        raise FleetError(f"{where}: top-level {', '.join(sorted(unknown))} is not supported")
    if not isinstance(doc.get("services"), dict) or not doc["services"]:
        raise FleetError(f"{where}: no services")
    for svc_name, svc in doc["services"].items():
        # A fragment may only run its own block, at the pinned version: that
        # is what makes the manifest's version the version on the device.
        if not isinstance(svc, dict) or svc.get("image") != image:
            raise FleetError(f"{where}: service {svc_name} must use image {image}")
    return doc


def render(root: Path, fleet: dict) -> dict:
    """The fleet's composition and release metadata, as file contents."""
    compose = {"version": None, "volumes": {}, "services": {}}
    owner = {}
    for name, version in fleet["services"].items():
        doc = _service_compose(root, name, version)
        where = f"services/{name}/{version}/docker-compose.yml"
        doc_version = doc.get("version")
        if compose["version"] is None:
            compose["version"] = doc_version
        elif doc_version != compose["version"]:
            raise FleetError(
                f"{where}: compose version {doc_version!r} differs from "
                f"{compose['version']!r} in the other services of fleet {fleet['id']}"
            )
        # Service and volume names share one namespace per fleet. A clash
        # would silently replace one project's container or data with
        # another's, so it is an error naming both owners.
        for kind in ("services", "volumes"):
            for key, value in (doc.get(kind) or {}).items():
                previous = owner.get((kind, key))
                if previous is not None:
                    raise FleetError(
                        f"fleet {fleet['id']}: {kind[:-1]} {key!r} is defined by both "
                        f"{previous} and {name}"
                    )
                owner[(kind, key)] = name
                compose[kind][key] = value
    if compose["version"] is None:
        del compose["version"]
    if not compose["volumes"]:
        del compose["volumes"]
    # Same key order as the fragments: version, volumes, services.
    compose_text = GENERATED_HEADER.format(id=fleet["id"]) + yaml.safe_dump(
        compose, sort_keys=False, default_flow_style=False
    )

    pinned = ", ".join(f"{n} {v}" for n, v in fleet["services"].items())
    balena_yml = yaml.safe_dump(
        {
            "name": fleet["name"],
            "type": "sw.application",
            "version": fleet["version"],
            "description": f"{fleet['name']} {fleet['version']}: {pinned}.",
        },
        sort_keys=False,
        default_flow_style=False,
    )

    # Release tags on the balena release, so the dashboard says which version
    # of every service a fleet release runs without leaving balenaCloud.
    tags = [[name, version] for name, version in fleet["services"].items()]
    meta = {
        "id": fleet["id"],
        "name": fleet["name"],
        "slug": fleet["slug"],
        "version": fleet["version"],
        "deploy": fleet["deploy"],
        "services": fleet["services"],
        "release_tags": tags,
    }
    return {"docker-compose.yml": compose_text, "balena.yml": balena_yml, "meta": meta}


def check(root: Path, base_root: Path | None = None) -> list:
    """Every problem with the fleets under root, as messages; empty when clean."""
    problems = []
    ids = fleet_ids(root)
    if not ids:
        problems.append(f"{root / 'fleets'}: no fleet manifests")
    for fleet_id in ids:
        try:
            fleet = load_fleet(root, fleet_id)
            rendered = render(root, fleet)
        except FleetError as exc:
            problems.append(str(exc))
            continue
        if base_root is None:
            continue
        try:
            base_fleet = load_fleet(base_root, fleet_id)
            base_rendered = render(base_root, base_fleet)
        except FleetError:
            # New at this change, or unrenderable at the base: nothing to
            # compare the version against.
            continue
        head_v, base_v = semver(fleet["version"]), semver(base_fleet["version"])
        if head_v < base_v:
            problems.append(
                f"fleets/{fleet_id}.yml: version {fleet['version']} is lower than "
                f"{base_fleet['version']} on the base branch"
            )
        elif rendered["docker-compose.yml"] != base_rendered["docker-compose.yml"] and head_v == base_v:
            problems.append(
                f"fleets/{fleet_id}.yml: the rendered composition changed but version "
                f"is still {fleet['version']}; raise it (patch, minor or major, as the "
                f"service versions moved)"
            )
    return problems


def changed(root: Path, base_root: Path) -> list:
    """Fleet ids a merge from base_root to root should push."""
    result = []
    for fleet_id in fleet_ids(root):
        fleet = load_fleet(root, fleet_id)
        if not fleet["deploy"]:
            continue
        head = render(root, fleet)
        try:
            base_fleet = load_fleet(base_root, fleet_id)
            base = render(base_root, base_fleet)
        except FleetError:
            result.append(fleet_id)
            continue
        if not base_fleet["deploy"]:
            result.append(fleet_id)
        elif (head["docker-compose.yml"], head["balena.yml"]) != (
            base["docker-compose.yml"],
            base["balena.yml"],
        ):
            result.append(fleet_id)
    return result


def write_render(root: Path, fleet_id: str, out: Path) -> Path:
    fleet = load_fleet(root, fleet_id)
    rendered = render(root, fleet)
    target = out / fleet_id
    source = target / "source"
    source.mkdir(parents=True, exist_ok=True)
    (source / "docker-compose.yml").write_text(rendered["docker-compose.yml"], encoding="utf-8")
    (source / "balena.yml").write_text(rendered["balena.yml"], encoding="utf-8")
    (target / "meta.json").write_text(json.dumps(rendered["meta"], indent=2) + "\n", encoding="utf-8")
    return target


def main(argv: list | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=ROOT, help="repository tree to read (default: this one)")
    sub = parser.add_subparsers(dest="command", required=True)

    p_check = sub.add_parser("check", help="validate every fleet")
    p_check.add_argument("--base-root", type=Path, help="base branch tree, to require version bumps")

    p_render = sub.add_parser("render", help="write fleet push sources")
    p_render.add_argument("ids", nargs="*", help="fleet ids (default: all)")
    p_render.add_argument("--out", type=Path, required=True)

    p_changed = sub.add_parser("changed", help="fleets a merge should push")
    p_changed.add_argument("--base-root", type=Path, required=True)

    args = parser.parse_args(argv)
    try:
        if args.command == "check":
            problems = check(args.root, args.base_root)
            for problem in problems:
                print(f"error: {problem}", file=sys.stderr)
            if problems:
                return 1
            print(f"ok: {len(fleet_ids(args.root))} fleet(s) render cleanly")
        elif args.command == "render":
            for fleet_id in args.ids or fleet_ids(args.root):
                print(write_render(args.root, fleet_id, args.out))
        elif args.command == "changed":
            for fleet_id in changed(args.root, args.base_root):
                print(fleet_id)
    except FleetError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
